import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { summarizeReport } from './results.js';

/**
 * @import { UiSuite } from '@dops/core'
 * @import { Failure, Stats } from './results.js'
 */

/**
 * @typedef {object} UiTestRun
 * @property {string} id
 * @property {string} suite
 * @property {'passed' | 'failed' | 'error'} status
 * @property {string} startedAt
 * @property {string} finishedAt
 * @property {Stats} [stats]
 * @property {Failure[]} failures
 * @property {string} reportDir  Playwright HTML report.
 * @property {string} [error]   Set when Playwright could not run at all.
 */

const require = createRequire(import.meta.url);

/** @param {Date} date */
export function runId(date = new Date()) {
  return `${date.toISOString().slice(0, 19).replace(/[-:T]/g, '')}-${randomBytes(2).toString('hex')}`;
}

/**
 * Playwright config for one run. Generated so that suites only need spec files.
 *
 * @param {UiSuite} suite
 * @param {string} runDir
 * @param {{ username: string, password: string }} [credentials]
 */
export function playwrightConfig(suite, runDir, credentials) {
  const config = {
    testDir: resolve(suite.testDir),
    outputDir: join(runDir, 'artifacts'),
    retries: suite.retries,
    workers: suite.workers,
    timeout: suite.timeoutSeconds * 1000,
    reporter: [
      ['json', { outputFile: join(runDir, 'results.json') }],
      ['html', { outputFolder: join(runDir, 'report'), open: 'never' }],
      ['line'],
    ],
    use: {
      baseURL: suite.baseUrl,
      ignoreHTTPSErrors: true,
      screenshot: 'only-on-failure',
      trace: 'retain-on-failure',
      ...(credentials ? { httpCredentials: credentials } : {}),
    },
  };
  return `// Generated by dops for this run.\nexport default ${JSON.stringify(config, null, 2)};\n`;
}

/**
 * @param {UiSuite} suite
 * @param {NodeJS.ProcessEnv} env
 */
function credentialsFor(suite, env) {
  if (!suite.httpAuth) return undefined;
  const username = env[suite.httpAuth.usernameEnv];
  const password = env[suite.httpAuth.passwordEnv];
  if (!username || !password) {
    throw new Error(
      `Basic auth needs ${suite.httpAuth.usernameEnv} and ${suite.httpAuth.passwordEnv} to be set`,
    );
  }
  return { username, password };
}

/**
 * Runs one suite with the Playwright test runner in a child process.
 *
 * @param {string} name
 * @param {UiSuite} suite
 * @param {object} options
 * @param {string} options.outputDir
 * @param {(chunk: string) => void} [options.onOutput]
 * @param {NodeJS.ProcessEnv} [options.env]
 * @param {AbortSignal} [options.signal]
 * @returns {Promise<UiTestRun>}
 */
export async function runSuite(name, suite, { outputDir, onOutput, env = process.env, signal }) {
  const startedAt = new Date();
  const id = runId(startedAt);
  const runDir = resolve(outputDir, name, id);
  await mkdir(runDir, { recursive: true });
  const base = {
    id,
    suite: name,
    startedAt: startedAt.toISOString(),
    reportDir: join(runDir, 'report'),
  };

  let code;
  try {
    const configFile = join(runDir, 'playwright.config.mjs');
    await writeFile(configFile, playwrightConfig(suite, runDir, credentialsFor(suite, env)));
    code = await new Promise((resolvePromise, reject) => {
      const child = spawn(
        process.execPath,
        [require.resolve('@playwright/test/cli'), 'test', '--config', configFile],
        { env: { ...env, FORCE_COLOR: '0' }, ...(signal ? { signal } : {}) },
      );
      child.stdout.on('data', (data) => onOutput?.(data.toString()));
      child.stderr.on('data', (data) => onOutput?.(data.toString()));
      child.on('error', reject);
      child.on('close', (exitCode) => resolvePromise(exitCode ?? 1));
    });
  } catch (error) {
    return {
      ...base,
      status: 'error',
      finishedAt: new Date().toISOString(),
      failures: [],
      error: error instanceof Error ? error.message : String(error),
    };
  }

  let summary;
  try {
    summary = summarizeReport(JSON.parse(await readFile(join(runDir, 'results.json'), 'utf8')));
  } catch {
    return {
      ...base,
      status: 'error',
      finishedAt: new Date().toISOString(),
      failures: [],
      error: `Playwright exited with ${code} without a report`,
    };
  }
  // A non-zero exit without failing tests means Playwright was interrupted or broke.
  const interrupted = !summary.stats.failed && code !== 0;
  return {
    ...base,
    status: summary.stats.failed ? 'failed' : interrupted ? 'error' : 'passed',
    finishedAt: new Date().toISOString(),
    ...summary,
    ...(interrupted ? { error: `Playwright exited with ${code}` } : {}),
  };
}
