import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join, normalize, relative, resolve } from 'node:path';
import { devices } from '@playwright/test';
import { summarizeReport } from './results.js';

/**
 * @import { UiRunOptions, UiSuite } from '@dops/core'
 * @import { Failure, Stats } from './results.js'
 */

/**
 * @typedef {object} UiTestRun
 * @property {string} id
 * @property {string} suite
 * @property {'passed' | 'failed' | 'error' | 'cancelled'} status
 * @property {string} startedAt
 * @property {string} finishedAt
 * @property {Stats} [stats]
 * @property {Failure[]} failures
 * @property {string} reportDir  Playwright HTML report.
 * @property {string} [error]   Set when Playwright could not run at all.
 * @property {string} [testFile]
 * @property {string} [environment]
 * @property {string} [baseUrl]
 * @property {string[]} [urls]
 * @property {string} [browser]
 * @property {string} [trigger] "manual", "cli" or "schedule:<name>".
 */

const require = createRequire(import.meta.url);

/** @param {Date} date */
export function runId(date = new Date()) {
  return `${date.toISOString().slice(0, 19).replace(/[-:T]/g, '')}-${randomBytes(2).toString('hex')}`;
}

/**
 * Playwright config for one run. Generated so that suites only need spec files.
 *
 * @param {UiSuite} suite
 * @param {string} runDir
 * @param {{ username: string, password: string }} [credentials]
 * @param {{ baseUrl?: string, browser?: UiRunOptions['browser'] }} [options]
 */
export function playwrightConfig(
  suite,
  runDir,
  credentials,
  { baseUrl = suite.baseUrl, browser = 'chromium' } = {},
) {
  const config = {
    testDir: resolve(suite.testDir),
    outputDir: join(runDir, 'artifacts'),
    retries: suite.retries,
    workers: suite.workers,
    timeout: suite.timeoutSeconds * 1000,
    reporter: [
      ['json', { outputFile: join(runDir, 'results.json') }],
      ['html', { outputFolder: join(runDir, 'report'), open: 'never' }],
      ['line'],
    ],
    use: {
      ...browserSettings(browser),
      baseURL: baseUrl,
      ignoreHTTPSErrors: true,
      screenshot: 'only-on-failure',
      trace: 'retain-on-failure',
      ...(credentials ? { httpCredentials: credentials } : {}),
    },
  };
  return `// Generated by dops for this run.\nexport default ${JSON.stringify(config, null, 2)};\n`;
}

/**
 * Playwright `use` settings for a browser choice; "mobile" emulates a phone in Chromium.
 *
 * @param {UiRunOptions['browser']} browser
 */
export function browserSettings(browser = 'chromium') {
  // The device descriptor sets viewport, user agent, touch and Chromium as the browser.
  if (browser === 'mobile') return { ...devices['Pixel 7'] };
  return { browserName: browser };
}

/**
 * Spec files of a suite, relative to its testDir.
 *
 * @param {UiSuite} suite
 * @returns {Promise<string[]>}
 */
export async function listTestFiles(suite) {
  const root = resolve(suite.testDir);
  if (!existsSync(root)) return [];
  const entries = await readdir(root, { recursive: true });
  return entries
    .map((entry) => String(entry))
    .filter((file) => /\.(spec|test)\.[cm]?[jt]s$/.test(file) && !file.includes('node_modules'))
    .sort();
}

/**
 * Checks that a spec file lies inside the suite's folder and exists.
 *
 * @param {UiSuite} suite
 * @param {string} file
 */
function resolveTestFile(suite, file) {
  const root = resolve(suite.testDir);
  const path = resolve(root, normalize(file));
  if (relative(root, path).startsWith('..') || !existsSync(path)) {
    throw new Error(`No test file "${file}" in ${suite.testDir}`);
  }
  return path;
}

/**
 * @param {UiSuite} suite
 * @param {NodeJS.ProcessEnv} env
 */
function credentialsFor(suite, env) {
  if (!suite.httpAuth) return undefined;
  const username = env[suite.httpAuth.usernameEnv];
  const password = env[suite.httpAuth.passwordEnv];
  if (!username || !password) {
    throw new Error(
      `Basic auth needs ${suite.httpAuth.usernameEnv} and ${suite.httpAuth.passwordEnv} to be set`,
    );
  }
  return { username, password };
}

/**
 * Runs one suite (or one spec file of it) with the Playwright test runner in a
 * child process.
 *
 * @param {string} name
 * @param {UiSuite} suite
 * @param {UiRunOptions & {
 *   outputDir: string,
 *   onOutput?: (chunk: string) => void,
 *   env?: NodeJS.ProcessEnv,
 *   signal?: AbortSignal,
 *   trigger?: string,
 * }} options
 * @returns {Promise<UiTestRun>}
 */
export async function runSuite(name, suite, options) {
  const { outputDir, onOutput, env = process.env, signal } = options;
  const startedAt = new Date();
  const id = runId(startedAt);
  const runDir = resolve(outputDir, name, id);
  await mkdir(runDir, { recursive: true });
  const baseUrl = options.environment ? suite.environments[options.environment] : suite.baseUrl;
  const urls = options.urls?.filter(Boolean) ?? [];
  const base = {
    id,
    suite: name,
    startedAt: startedAt.toISOString(),
    reportDir: join(runDir, 'report'),
    ...(options.testFile ? { testFile: options.testFile } : {}),
    ...(options.environment ? { environment: options.environment } : {}),
    ...(baseUrl ? { baseUrl } : {}),
    ...(urls.length ? { urls } : {}),
    browser: options.browser ?? 'chromium',
    trigger: options.trigger ?? 'manual',
  };

  let code;
  try {
    if (!baseUrl) throw new Error(`Unknown environment "${options.environment}"`);
    const args = [require.resolve('@playwright/test/cli'), 'test'];
    if (options.testFile) args.push(resolveTestFile(suite, options.testFile));
    const configFile = join(runDir, 'playwright.config.mjs');
    await writeFile(
      configFile,
      playwrightConfig(suite, runDir, credentialsFor(suite, env), {
        baseUrl,
        ...(options.browser ? { browser: options.browser } : {}),
      }),
    );
    args.push('--config', configFile);
    code = await new Promise((resolvePromise, reject) => {
      const child = spawn(process.execPath, args, {
        env: {
          ...env,
          FORCE_COLOR: '0',
          DOPS_BASE_URL: baseUrl,
          ...(urls.length ? { DOPS_TEST_URLS: urls.join(',') } : {}),
        },
        ...(signal ? { signal } : {}),
      });
      child.stdout.on('data', (data) => onOutput?.(data.toString()));
      child.stderr.on('data', (data) => onOutput?.(data.toString()));
      child.on('error', reject);
      child.on('close', (exitCode) => resolvePromise(exitCode ?? 1));
    });
  } catch (error) {
    if (signal?.aborted) {
      return { ...base, status: 'cancelled', finishedAt: new Date().toISOString(), failures: [] };
    }
    return {
      ...base,
      status: 'error',
      finishedAt: new Date().toISOString(),
      failures: [],
      error: error instanceof Error ? error.message : String(error),
    };
  }

  let summary;
  try {
    summary = summarizeReport(JSON.parse(await readFile(join(runDir, 'results.json'), 'utf8')));
  } catch {
    return {
      ...base,
      status: 'error',
      finishedAt: new Date().toISOString(),
      failures: [],
      error: `Playwright exited with ${code} without a report`,
    };
  }
  // A non-zero exit without failing tests means Playwright was interrupted or broke.
  const interrupted = !summary.stats.failed && code !== 0;
  return {
    ...base,
    status: summary.stats.failed ? 'failed' : interrupted ? 'error' : 'passed',
    finishedAt: new Date().toISOString(),
    ...summary,
    ...(interrupted ? { error: `Playwright exited with ${code}` } : {}),
  };
}
